    # ── Async Helpers with Automatic Model Fallback ──

    def _is_retriable(self, error: Exception) -> bool:
        s = str(error)
        return "429" in s or "503" in s or "UNAVAILABLE" in s or "quota" in s.lower()

    async def _send_async(self, chat, message: str) -> str:
        """Send a message to a Gemini chat session."""
        import asyncio
        loop = asyncio.get_event_loop()
        response = await loop.run_in_executor(
            None, lambda: chat.send_message(message)
        )
        return response.text

    async def _generate_async(self, prompt: str, config_override: dict = None) -> str:
        """Generate content, automatically trying fallback models on failure."""
        import asyncio

        base_config = {"system_instruction": SYSTEM_PROMPT, "temperature": 0.7, "top_p": 0.9, "max_output_tokens": 2048}
        if config_override:
            base_config.update(config_override)

        models_tried = set()
        last_error = None
        max_attempts = len(FALLBACK_MODELS) + 1

        for _ in range(max_attempts):
            model = self._pick_model()
            if model is None or model in models_tried:
                break
            models_tried.add(model)
            try:
                loop = asyncio.get_event_loop()
                current_model = model
                response = await loop.run_in_executor(
                    None,
                    lambda m=current_model, cfg=base_config.copy(): self._client.models.generate_content(
                        model=m, contents=prompt, config=cfg,
                    ),
                )
                if current_model != self._model_name:
                    print(f"[GeminiAdvisor] Succeeded with fallback model: {current_model}")
                self._active_model = current_model
                return response.text
            except Exception as e:
                last_error = e
                self._handle_rate_limit(e, model)
                if self._is_retriable(e):
                    print(f"[GeminiAdvisor] {model} failed, trying next fallback...")
                    continue
                raise

        if last_error:
            raise last_error
        raise RuntimeError("All Gemini models are rate-limited. Please wait a few minutes.")

