def _build_sensor_context() -> str:
    """Build a rich text snapshot of all current greenhouse data for Gemini."""
    latest = tsdb.get_all_latest()
    if not latest:
        return "No sensor data available yet. The system is still initializing."

    lines = ["## Current Greenhouse Sensor Data (Live)"]
    lines.append(f"Timestamp: {get_now().isoformat()}\n")

    zone_map = {}
    for key, reading in latest.items():
        zone_id = reading.zone_id
        if zone_id not in zone_map:
            zone_map[zone_id] = []
        zone_map[zone_id].append(reading)

    zone_labels = {
        "zone_air": "Greenhouse Condition",
        "zone_bed_a": "Substrate A",
        "zone_bed_b": "Substrate B",
        "zone_bed_c": "Substrate C",
    }

    for zone_id, readings in zone_map.items():
        lines.append(f"### {zone_labels.get(zone_id, zone_id)}")
        for r in readings:
            trend = _get_trend(zone_id, r.sensor_type.value)
            quality_flag = " [LOW QUALITY]" if r.quality < 0.5 else ""
            lines.append(f"- {r.sensor_type.value}: {r.value} {r.unit} (trend: {trend}){quality_flag}")
        lines.append("")

    # VPD calculation — prefer air temperature, fall back to avg soil temp
    air_temp_r = tsdb.get_latest("zone_air", "temperature")
    rh_r = tsdb.get_latest("zone_air", "humidity")
    if air_temp_r and rh_r:
        avg_temp = air_temp_r.value
        vpd = calculate_vpd(avg_temp, rh_r.value)
        dp = calculate_dew_point(avg_temp, rh_r.value)
        lines.append(f"### Derived Metrics")
        lines.append(f"- VPD: {vpd} kPa (air temp {avg_temp:.1f}°C)")
        lines.append(f"- Dew Point: {dp}°C")
        lines.append("")
    else:
        soil_temps = [
            tsdb.get_latest(f"zone_bed_{bed}", "soil_temperature")
            for bed in ("a", "b", "c")
        ]
        valid_temps = [r for r in soil_temps if r is not None]
        if valid_temps and rh_r:
            avg_temp = sum(r.value for r in valid_temps) / len(valid_temps)
            vpd = calculate_vpd(avg_temp, rh_r.value)
            dp = calculate_dew_point(avg_temp, rh_r.value)
            lines.append(f"### Derived Metrics")
            lines.append(f"- VPD: {vpd} kPa (using avg soil temp {avg_temp:.1f}°C as proxy)")
            lines.append(f"- Dew Point: {dp}°C")
            lines.append("")

    # Actuator states
    actuators = twin_state.get_all_actuators()
    if actuators:
        lines.append("### Actuator States")
        for a in actuators:
            lines.append(f"- {a.name} ({a.actuator_id}): {a.state.value}")
        lines.append("")

    # Active alerts
    alerts = twin_state.get_alerts()
    if alerts:
        lines.append(f"### Active Alerts ({len(alerts)})")
        for al in alerts[:10]:
            lines.append(f"- [{al.severity.value.upper()}] {al.message}")
        lines.append("")

    # Outdoor weather (Open-Meteo) — helps Gemini reason about indoor vs outdoor
    try:
        weather = weather_service.get_weather()
        cur = weather.get("current", {}) or {}
        nxt = weather.get("next_12h", {}) or {}
        if cur:
            lines.append("### Outdoor Weather (Live)")
            lines.append(f"- Condition: {cur.get('condition', 'n/a')}")
            if cur.get("temp_c") is not None:
                lines.append(f"- Outdoor temp: {cur['temp_c']}°C")
            if cur.get("humidity_pct") is not None:
                lines.append(f"- Outdoor humidity: {cur['humidity_pct']}%")
            if cur.get("cloud_cover_pct") is not None:
                lines.append(f"- Cloud cover: {cur['cloud_cover_pct']}%")
            if cur.get("wind_kmh") is not None:
                lines.append(f"- Wind: {cur['wind_kmh']} km/h")
            lines.append("")
        if nxt and nxt.get("max_temp_c") is not None:
            lines.append("### 12-Hour Weather Forecast")
            lines.append(f"- Temp range: {nxt.get('min_temp_c')}°C — {nxt.get('max_temp_c')}°C")
            lines.append(f"- Max rain probability: {nxt.get('max_rain_prob_pct', 0)}%")
            lines.append(f"- Total expected rain: {nxt.get('total_rain_mm', 0)} mm")
            lines.append("")
    except Exception as e:
        print(f"[GeminiAdvisor] Weather context error: {e}")

    # Active crop
    crop = rule_advisor.get_crop_profile()
    lines.append(f"### Active Crop Profile: {crop.name}")
    lines.append(f"- Ideal temp: {crop.temp_min}-{crop.temp_max}°C (best: {crop.temp_ideal}°C)")
    lines.append(f"- Ideal humidity: {crop.rh_min}-{crop.rh_max}%")
    lines.append(f"- Ideal pH: {crop.ph_min}-{crop.ph_max}")
    lines.append(f"- Ideal EC: {crop.ec_min}-{crop.ec_max} mS/cm")
    lines.append(f"- Ideal VPD: {crop.vpd_min}-{crop.vpd_max} kPa")
    lines.append(f"- Light: {crop.light_hours}h/day, DLI target: {crop.light_dli} mol/m²/day")
    lines.append(f"- Notes: {crop.notes}")

    return "\n".join(lines)


def _build_history_context(zone_id: str, sensor_type: str, count: int = 30) -> str:
    """Get recent history for a sensor as text."""
    history = tsdb.get_recent_values(zone_id, sensor_type, count=count)
    if not history:
        return "No historical data."
    values = [v for _, v in history]
    arr = np.array(values)
    return (
        f"Last {len(values)} readings — "
        f"min: {arr.min():.1f}, max: {arr.max():.1f}, "
        f"mean: {arr.mean():.1f}, std: {arr.std():.2f}, "
        f"latest: {values[-1]:.1f}"
    )


def _get_trend(zone_id: str, sensor_type: str) -> str:
    history = tsdb.get_recent_values(zone_id, sensor_type, count=20)
    if len(history) < 5:
        return "insufficient data"
    values = [v for _, v in history]
    slope = (values[-1] - values[0]) / len(values)
    if abs(slope) < 0.05:
        return "stable"
    return "rising" if slope > 0 else "falling"


class GeminiAdvisor:
    """Google Gemini-powered greenhouse AI advisor with automatic model fallback."""

    def __init__(self):
        self._client = None
        self._chat_sessions: Dict[str, object] = {}
        self._conversation_history: deque = deque(maxlen=50)
        self._initialized = False
        self._init_error = None
        self._cache: Dict[str, Tuple[float, dict]] = {}
        self._model_name = ""
        self._active_model = ""
        self._blocked_models: Dict[str, float] = {}
        self._rate_limit_until = 0.0
        self._initialize()

    def _get_cached(self, key: str) -> Optional[dict]:
        if key in self._cache:
            ts, data = self._cache[key]
            if time.time() - ts < CACHE_TTL_SECONDS:
                return data
            del self._cache[key]
        return None

    def _set_cache(self, key: str, data: dict):
        self._cache[key] = (time.time(), data)

    def _check_rate_limit(self) -> bool:
        return time.time() < self._rate_limit_until

    def _handle_rate_limit(self, error: Exception, model: str = ""):
        """Block the specific model that hit a rate/availability limit."""
        error_str = str(error)
        target = model or self._active_model
        is_rate_limit = "429" in error_str or "quota" in error_str.lower()
        is_unavailable = "503" in error_str or "UNAVAILABLE" in error_str

        if is_rate_limit:
            is_daily = "PerDay" in error_str
            cooldown = 3600 if is_daily else 60
            self._blocked_models[target] = time.time() + cooldown
            print(f"[GeminiAdvisor] {target} blocked {cooldown}s ({'daily' if is_daily else 'per-min'} limit)")
        elif is_unavailable:
            self._blocked_models[target] = time.time() + 30
            print(f"[GeminiAdvisor] {target} temporarily unavailable, blocked 30s")

    def _pick_model(self) -> Optional[str]:
        """Pick the best available model, skipping blocked ones."""
        now = time.time()
        preferred = self._model_name
        if preferred not in self._blocked_models or now >= self._blocked_models[preferred]:
            self._blocked_models.pop(preferred, None)
            return preferred
        for model in FALLBACK_MODELS:
            if model not in self._blocked_models or now >= self._blocked_models[model]:
                self._blocked_models.pop(model, None)
                return model
        return None

    def _initialize(self):
        if not settings.gcp_project_id:
            self._init_error = "GCP Project ID not configured"
            return

        try:
            from google import genai
            self._client = genai.Client(
                vertexai=True, 
                project=settings.gcp_project_id, 
                location=settings.gcp_location
            )
            self._model_name = settings.gemini_model
            self._active_model = settings.gemini_model
            self._initialized = True
            print(f"[GeminiAdvisor] Initialized Vertex AI — primary: {settings.gemini_model}, fallbacks: {FALLBACK_MODELS}")
        except Exception as e:
            self._init_error = str(e)
            print(f"[GeminiAdvisor] Init error: {e}")

    @property
    def is_available(self) -> bool:
        return self._initialized and self._client is not None

    def _get_or_create_chat(self, session_id: str = "default"):
        if session_id not in self._chat_sessions:
            self._chat_sessions[session_id] = self._client.chats.create(
                model=self._model_name,
                config={"system_instruction": SYSTEM_PROMPT, **self._gen_config},
            )
        return self._chat_sessions[session_id]

    def clear_chat(self, session_id: str = "default"):
        self._chat_sessions.pop(session_id, None)

    # ── Core Chat ──

    async def chat(self, user_message: str, session_id: str = "default") -> dict:
        """Main conversational endpoint. Every call includes live sensor context."""
        if not self.is_available:
            return self._fallback_response(user_message)

        try:
            context = _build_sensor_context()

            recent_block = ""
            history_text = ""
            recent = list(self._conversation_history)[-6:]
            for entry in recent:
                role_tag = "User" if entry["role"] == "user" else "GreenMind"
                history_text += f"**{role_tag}**: {entry['text'][:200]}\n\n"

            enriched_prompt = (
                f"{context}\n\n---\n\n"
                f"{recent_block}"
                f"**User Question**: {user_message}\n\n"
                f"Respond as GreenMind. Use the live sensor data above to give specific, "
                f"data-driven advice. Reference actual values."
            )

            response = await self._generate_async(enriched_prompt)

            self._conversation_history.append({
                "role": "user", "text": user_message,
                "timestamp": get_now().isoformat(),
            })
            self._conversation_history.append({
                "role": "assistant", "text": response,
                "timestamp": get_now().isoformat(),
            })

            return {
                "answer": response,
                "model": self._active_model,
                "powered_by": "google_gemini",
            }
        except Exception as e:
            print(f"[GeminiAdvisor] Chat error: {e}")
            return self._fallback_response(user_message)

